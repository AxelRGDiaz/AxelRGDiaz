def text(s, x, y, px, color, extra=""):
    """Devuelve un <path> con todos los pixeles del texto (un solo nodo, SVG ligero)."""
    d = []
    for i, ch in enumerate(s):
        g = F[ch]
        ox = x + i * 6 * px
        for r, row in enumerate(g):
            for c, bit in enumerate(row):
                if bit == "1":
                    d.append(f"M{ox + c*px} {y + r*px}h{px}v{px}h-{px}z")
    return f'<path {extra} fill="{color}" d="{"".join(d)}"/>'

